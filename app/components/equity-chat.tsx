function welcomeMessage(language: Language): ChatMessage {
  return {
    id: "welcome",
    role: "assistant",
    text:
      language === "es"
        ? "Hola, soy Equa. Estoy aquí para ayudarte a entender la igualdad de género desde la historia, los datos y la vida cotidiana. ¿Por dónde empezamos?"
        : "Hi, I’m Equa. I’m here to help you understand gender equality through history, data and everyday life. Where should we begin?",
    source: "demo",
  };
}

