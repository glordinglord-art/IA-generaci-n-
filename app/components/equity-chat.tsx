export function EquityChat() {
  const [language, setLanguage] = useState<Language>("es");
  const [messages, setMessages] = useState<ChatMessage[]>([welcomeMessage("es")]);
  const [input, setInput] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const t = copy[language];

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }, [messages, isLoading]);

  function changeLanguage(nextLanguage: Language) {
    setLanguage(nextLanguage);
    setMessages((current) =>
      current.length === 1 && current[0].id === "welcome"
        ? [welcomeMessage(nextLanguage)]
        : current,
    );
    setSidebarOpen(false);
  }

  function newConversation() {
    setMessages([welcomeMessage(language)]);
    setInput("");
    setSidebarOpen(false);
  }

  async function submitMessage(rawMessage: string) {
    const message = rawMessage.trim();
    if (!message || isLoading) return;

    const history = messages.filter((item) => item.id !== "welcome");
    const userMessage: ChatMessage = {
      id: `${Date.now()}-user`,
      role: "user",
      text: message,
    };

    setMessages((current) => [...current, userMessage]);
    setInput("");
    setIsLoading(true);

    try {
      const response = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ message, language, history, modelMode: "auto" }),
      });
      const data = (await response.json()) as { answer?: string; source?: "gemini" | "demo"; model?: string };

      if (!response.ok || !data.answer) throw new Error("chat_request_failed");

      setMessages((current) => [
        ...current,
        {
          id: `${Date.now()}-assistant`,
          role: "assistant",
          text: data.answer ?? t.error,
          source: data.source ?? "demo",
        },
      ]);
    } catch {
      setMessages((current) => [
        ...current,
        {
          id: `${Date.now()}-error`,
          role: "assistant",
          text: t.error,
          source: "demo",
        },
      ]);
    } finally {
      setIsLoading(false);
    }
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void submitMessage(input);
  }

  function handleKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      void submitMessage(input);
    }
  }

  return (
    <div className="app-shell">
      {sidebarOpen && <button className="mobile-overlay" aria-label="Cerrar menú" onClick={() => setSidebarOpen(false)} />}
      <aside className={`sidebar ${sidebarOpen ? "open" : ""}`}>
        <div className="brand"><span className="brand-mark"><Icon name="sparkle" size={16} /></span>Equa<span className="brand-dot">.</span></div>
        <button className="new-chat" onClick={newConversation}><Icon name="plus" size={15} />{t.newChat}</button>

        <nav className="sidebar-nav" aria-label={t.explore}>
          <span className="nav-caption">{t.explore}</span>
          <button className="nav-link active" onClick={newConversation}><Icon name="chat" size={16} />{t.conversation}</button>
          <a className="nav-link" href="#impacto" onClick={() => setSidebarOpen(false)}><Icon name="book" size={16} />{t.resources}</a>
          <a className="nav-link" href="#sobre" onClick={() => setSidebarOpen(false)}><Icon name="info" size={16} />{t.about}</a>
        </nav>

        <div className="sidebar-topics">
          <span className="nav-caption">{t.topics}</span>
          <button className="sidebar-topic" onClick={() => void submitMessage(prompts[language][0].label)}><span>{t.topicHistory}</span><span>01</span></button>
          <button className="sidebar-topic" onClick={() => void submitMessage(prompts[language][1].label)}><span>{t.topicWork}</span><span>02</span></button>
          <button className="sidebar-topic" onClick={() => void submitMessage(prompts[language][2].label)}><span>{t.topicCountries}</span><span>03</span></button>
        </div>

        <div className="sidebar-bottom">
          <div className="language-card">
            <Icon name="globe" size={16} />
            <div className="language-copy"><span className="language-label">{t.languageLabel}</span><span className="language-value">{t.languageValue}</span></div>
            <div className="language-toggle" role="group" aria-label={t.languageLabel}>
              <button className={language === "es" ? "active" : ""} onClick={() => changeLanguage("es")}>ES</button>
              <button className={language === "en" ? "active" : ""} onClick={() => changeLanguage("en")}>EN</button>
            </div>
          </div>
          <div className="profile-row"><span className="profile-avatar">{language === "es" ? "TÚ" : "YOU"}</span>{t.userName}</div>
        </div>
      </aside>

      <main className="main-content">
        <header className="topbar">
          <div className="topbar-context"><button className="mobile-menu" aria-label="Abrir menú" onClick={() => setSidebarOpen(true)}><Icon name="menu" size={17} /></button><span>Equa</span><span className="topbar-separator">/</span><strong>{t.context}</strong></div>
          <div className="topbar-right"><span className="ai-status"><i className="status-dot" />{t.active}</span><button className="topbar-help" onClick={() => document.getElementById("sobre")?.scrollIntoView()}><Icon name="info" size={14} />{t.help}</button></div>
        </header>

        <div className="content-wrap">
          <section className="intro-row" aria-labelledby="page-title">
            <div><div className="eyebrow"><span className="eyebrow-line" />{t.eyebrow}</div><h1 id="page-title" className="hero-title">{t.titleStart}<br /><em>{t.titleEnd}</em></h1><p className="hero-copy">{t.intro}</p></div>
            <div className="hero-mark" aria-hidden="true"><Icon name="heart" size={52} /></div>
          </section>

          <div className="workspace-grid">
            <section className="chat-card" aria-label={t.chatTitle}>
              <div className="chat-card-header"><div className="chat-card-title"><span className="chat-card-title-icon"><Icon name="sparkle" size={14} /></span>{t.chatTitle}</div><span className="chat-card-language">{t.chatLanguage}</span></div>
              <div className="messages" aria-live="polite">
                {messages.map((message) => (
                  <div className={`message-row ${message.role}`} key={message.id}>
                    <span className={`message-avatar ${message.role === "user" ? "user-avatar" : ""}`}>{message.role === "user" ? (language === "es" ? "TÚ" : "YOU") : <Icon name="sparkle" size={15} />}</span>
                    <div className="message-body"><div className="message-meta"><span>{message.role === "user" ? (language === "es" ? "Tú" : "You") : "Equa"}</span><span>·</span><span>{language === "es" ? "ahora" : "now"}</span></div><div className="message-bubble">{message.text}</div>{message.role === "assistant" && message.id !== "welcome" && <span className="message-source">{message.source === "gemini" ? t.sourceLabel : t.demoLabel}</span>}</div>
                  </div>
                ))}
                {isLoading && <div className="message-row"><span className="message-avatar"><Icon name="sparkle" size={15} /></span><div className="message-body"><div className="message-meta"><span>Equa</span><span>·</span><span>{language === "es" ? "pensando" : "thinking"}</span></div><div className="message-bubble"><span className="typing-dots"><i /><i /><i /></span></div></div></div>}
                <div ref={messagesEndRef} />
              </div>

              <div className="quick-prompts"><span className="quick-prompts-label">{t.exploreTopic}</span><div className="prompt-grid">{prompts[language].map((prompt) => <button className="prompt-chip" key={prompt.label} onClick={() => void submitMessage(prompt.label)}><Icon name={prompt.icon} size={14} />{prompt.label}</button>)}</div></div>
              <form className="composer" onSubmit={handleSubmit}><textarea value={input} onChange={(event) => setInput(event.target.value)} onKeyDown={handleKeyDown} placeholder={t.placeholder} aria-label={t.placeholder} rows={1} /><button className="send-button" type="submit" disabled={isLoading || !input.trim()} aria-label={language === "es" ? "Enviar pregunta" : "Send question"}><Icon name="send" size={16} /></button></form>
              <p className="disclaimer">{t.disclaimer}</p>
            </section>

            <aside className="insights-panel" id="impacto" aria-label={t.impactTitle}>
              <div className="panel-heading"><h2>{t.impactTitle}</h2><span>{t.impactSubtitle}</span></div>
              <div className="stat-grid"><div className="stat-card"><span className="stat-value">1945</span><p>{language === "es" ? "La igualdad se reconoce como derecho en la Carta de la ONU." : "Equality is recognized as a right in the UN Charter."}</p></div><div className="stat-card"><span className="stat-value">ODS 5</span><p>{language === "es" ? "Un objetivo global: lograr la igualdad y empoderar." : "A global goal: achieve equality and empower all."}</p></div><div className="stat-card"><span className="stat-value">∞</span><p>{language === "es" ? "La conversación sigue: cada generación puede ampliar el camino." : "The conversation continues: every generation can widen the path."}</p></div></div>
              <div className="impact-card"><div className="impact-title"><Icon name="target" size={15} />{t.impactTitle}</div><div className="impact-list"><div className="impact-row"><span>{t.rights}</span><span className="impact-track"><i style={{ width: "100%" }} /></span><strong>{t.rightsValue}</strong></div><div className="impact-row"><span>{t.education}</span><span className="impact-track"><i style={{ width: "80%" }} /></span><strong>{t.educationValue}</strong></div><div className="impact-row"><span>{t.work}</span><span className="impact-track"><i style={{ width: "65%" }} /></span><strong>{t.workValue}</strong></div></div></div>
              <div className="resource-card" id="sobre"><div className="impact-title"><Icon name="heart" size={15} />{t.factTitle}</div><p>{t.fact}</p><a href={language === "es" ? "https://www.unwomen.org/es" : "https://www.unwomen.org/en"} target="_blank" rel="noreferrer">{t.sourceLink}<Icon name="chevron" size={13} /></a></div>
            </aside>
          </div>
        </div>
      </main>
    </div>
  );
}
